import { createLeadChatRouter } from "./lead-chat";

const router: IRouter = Router();

// Pubbliche: healthcheck e login (/auth/me ha il suo requireAuth). Tutto il resto richiede una
// sessione o un token personale con l'ambito giusto (requireAuth).
router.use(healthRouter);
router.use(embedRouter);
router.use(embedBugsRouter);
router.use(authRouter());
// Protocollo dei nodi: solo token d'ambito `node` (requireNodeToken), mai sessione né token personali;
// va prima di requireAuth, che a sua volta rifiuta i token `node` su tutto il resto di /api.
router.use("/node", requireNodeToken, createNodeRouter());
// Abbinamento dei nodi: `start` e `poll` sono pubbliche (il nodo non ha ancora un token), con limiti propri.
router.use(createNodePairingPublicRouter());
router.use(requireAuth);
// Registro delle azioni: un evento per ogni risposta 2xx delle route sensibili (lib/audit/actions.ts)
router.use(auditRoutes());
router.use(embedStatusRouter);
router.use(appsRouter);
router.use(appToolsRouter);
router.use(appArchitectureRouter);
router.use(appEvolutionRouter);
router.use(appBootstrapsRouter);
router.use(appBugsRouter);
router.use(agentsRouter);
router.use(runsRouter);
router.use(createLiveRouter());
router.use(dashboardRouter);
router.use(budgetRouter);
