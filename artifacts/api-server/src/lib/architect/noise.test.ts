import { describe, expect, it } from "vitest";
import { isGeneratedText, isNoisePath } from "./noise";

describe("isNoisePath", () => {
  it.each([
    "pnpm-lock.yaml",
    "web/package-lock.json",
    "yarn.lock",
    "lib/api-client-react/src/generated/api.ts",
    "src/__tests__/a.ts",
    "src/a.test.ts",
    "src/a.spec.tsx",
    "public/app.min.js",
    "dist.js.map",
    "x/__snapshots__/a.snap",
  ])("%s è rumoroso", (p) => {
    expect(isNoisePath(p)).toBe(true);
  });

  it.each(["src/generator.ts", "src/testing-utils.ts", "src/latest.ts", "README.md"])("%s non lo è", (p) => {
    expect(isNoisePath(p)).toBe(false);
  });
});

describe("isGeneratedText", () => {
  it("riconosce l'intestazione di un file generato", () => {
    expect(isGeneratedText("// Code generated by orval. DO NOT EDIT.\nexport const a = 1;")).toBe(true);
  });
  it("non scambia un identificatore per un'intestazione", () => {
    expect(isGeneratedText("const generatedId = 1")).toBe(false);
  });
  it("guarda solo le prime 5 righe", () => {
    expect(isGeneratedText("a\nb\nc\nd\ne\n// generated by x")).toBe(false);
  });
});
