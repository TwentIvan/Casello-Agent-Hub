/**
 * File "rumorosi" per l'architetto: lockfile, generati, test, minificati. Elenchi e ricerche li
 * saltano per default (costano token e raramente servono a capire l'app); un file chiesto per
 * nome si legge sempre.
 */

const LOCKFILES = new Set(["pnpm-lock.yaml", "package-lock.json", "yarn.lock"]);
const NOISE_SEGMENTS = new Set(["generated", "test", "tests", "__tests__", "coverage"]);
const GENERATED_HEADER = /@generated|do not edit|auto-?generated|generated by/i;

export function isNoisePath(path: string): boolean {
  const parts = path.split("/");
  const base = parts[parts.length - 1]!;
  if (LOCKFILES.has(base)) return true;
  if (parts.some((seg) => NOISE_SEGMENTS.has(seg))) return true;
  if (base.includes(".min.")) return true;
  if (/\.(map|snap)$/.test(base)) return true;
  return /\.(test|spec)\.[^.]+$/.test(base);
}

/** Vero se le prime righe dichiarano il file generato (es. "Code generated by orval. DO NOT EDIT."). */
export function isGeneratedText(text: string): boolean {
  return GENERATED_HEADER.test(text.split("\n", 5).join("\n"));
}
